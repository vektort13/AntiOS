    language: str = "en"

    def t(self, key: str, **values: Any) -> str:
        lang = normalize_language(self.language)
        template = TRANSLATIONS.get(lang, {}).get(key)
        if template is None:
            template = TRANSLATIONS["en"].get(key, key)
